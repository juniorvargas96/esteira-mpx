@st.cache_resource(show_spinner=False)
def get_pool():
    url=st.secrets.get("DATABASE_URL","")
    if not url:
        raise RuntimeError("DATABASE_URL não configurada nos Secrets do Streamlit.")
    # Reaproveita conexões entre os reruns do Streamlit, evitando novo handshake
    # com o Supabase a cada clique.
    return ConnectionPool(
        conninfo=url,
        min_size=1,
        max_size=6,
        timeout=8,
        kwargs={"row_factory": dict_row},
        open=True,
    )

def con():
    return get_pool().connection()

def now(): return datetime.now().isoformat(timespec="seconds")
def sh(s): return hashlib.sha256(s.encode()).hexdigest()
def norm_login(s): return (s or "").strip().casefold()
def fmt(v):
    try:return datetime.fromisoformat(v).strftime("%d/%m/%Y %H:%M") if v else "—"
    except:return v or "—"
def fmt_data(v):
    if not v:return "—"
    try:
        if isinstance(v,str): return datetime.fromisoformat(v).strftime("%d/%m/%Y")
        return v.strftime("%d/%m/%Y")
    except:return str(v)
def age(v):
    if not v:return "—"
    try:m=max(0,int((datetime.now()-datetime.fromisoformat(v)).total_seconds()/60))
    except:return "—"
    if m<60:return f"{m} min"
    if m<1440:return f"{m//60}h {m%60:02d}min"
    return f"{m//1440}d {(m%1440)//60}h"

