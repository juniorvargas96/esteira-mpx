def finalizar(i,user,campos):
    with con() as c:
        a=c.execute("SELECT * FROM anuncios WHERE id=%s",(i,)).fetchone()
        p=c.execute("SELECT * FROM produtos WHERE sku=%s",(a["sku"],)).fetchone()
        etapa=a["etapa"]
        if etapa=="DIMENSÕES":
            if any(float(campos.get(k,0) or 0)<=0 for k in ["altura","largura","comprimento","peso"]):
                return "Preencha altura, largura, comprimento e peso."
            c.execute("UPDATE produtos SET altura=%s,largura=%s,comprimento=%s,peso=%s WHERE sku=%s",
                      (campos["altura"],campos["largura"],campos["comprimento"],campos["peso"],a["sku"]))
        elif etapa=="VÍDEO":
            if not campos.get("video","").strip(): return "Informe o link do vídeo."
            c.execute("UPDATE produtos SET video_padrao=%s WHERE sku=%s",(campos["video"].strip(),a["sku"]))
            c.execute("UPDATE anuncios SET link_video=%s WHERE id=%s",(campos["video"].strip(),i))
        elif etapa=="CRIAR ANÚNCIO":
            c.execute("UPDATE anuncios SET link_anuncio=%s WHERE id=%s",(campos.get("link_anuncio","").strip() or None,i))

        t=now(); log(c,i,etapa,"ETAPA CONCLUÍDA",user["nome"])
        retorno=a["correcao_retorno"] or a["correcao_origem"]
        corr=bool(a["correcao_retorno"] or a["correcao_origem"] or a["correcao_destino"])
        if corr and retorno:
            c.execute("""UPDATE anuncios SET etapa=%s,status='AGUARDANDO',responsavel=NULL,entrada_etapa_em=%s,
                inicio_etapa_em=NULL,atualizado_em=%s,correcao_origem=NULL,correcao_destino=NULL,
                correcao_retorno=NULL,correcao_motivo=NULL WHERE id=%s""",(retorno,t,t,i))
            log(c,i,retorno,"CORREÇÃO CONCLUÍDA / RETORNO DIRETO",user["nome"])
            return None
        k=ETAPAS.index(etapa)
        if k==len(ETAPAS)-1:
            c.execute("UPDATE anuncios SET status='OK',responsavel=%s,atualizado_em=%s WHERE id=%s",(user["nome"],t,i))
            log(c,i,"ADS","ANÚNCIO FINALIZADO",user["nome"])
        else:
            prox=ETAPAS[k+1]
            c.execute("""UPDATE anuncios SET etapa=%s,status='AGUARDANDO',responsavel=NULL,
                entrada_etapa_em=%s,inicio_etapa_em=NULL,atualizado_em=%s WHERE id=%s""",(prox,t,t,i))
            log(c,i,prox,"TRABALHO RECEBIDO",a["canal"] or "")
    return None

