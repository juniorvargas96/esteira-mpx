def resumo_anuncio(a,p,titulos):
    st.markdown(f"**Canal:** {a['canal'] or '—'}")
    st.markdown("**Título(s):**")
    for i,t in enumerate(titulos,1):
        st.write(f"{i}. {t}")
        st.caption(f"{len(t)} caracteres")
    desc=(p["descricao"] if p else "") or a.get("descricao") or ""
    st.markdown(f"**Descrição:** {len(desc)} caracteres")
    st.text_area("Descrição cadastrada",desc,height=120,disabled=True,key=f"resdesc_{a['id']}_{a['etapa']}")
    canal=(a["canal"] or "")
    if canal.startswith("MERCADO LIVRE"):
        c1,c2=st.columns(2)
        c1.metric("Preço Premium",f"R$ {float(a['preco_premium'] or 0):,.2f}".replace(",", "X").replace(".",",").replace("X","."))
        c2.metric("Preço Clássico",f"R$ {float(a['preco_classico'] or 0):,.2f}".replace(",", "X").replace(".",",").replace("X","."))
    elif canal.startswith("SHOPEE"):
        st.metric("Preço Shopee",f"R$ {float(a['preco_shopee'] or 0):,.2f}".replace(",", "X").replace(".",",").replace("X","."))
    elif canal.startswith("TIKTOK"):
        st.metric("Preço TikTok Shop",f"R$ {float(a['preco_tiktok'] or 0):,.2f}".replace(",", "X").replace(".",",").replace("X","."))
    st.caption(f"Prioridade: {a['prioridade']} · Prazo: {fmt_data(a['prazo'])}")

def criar_produto(sku,canais,q_ml,titulos_ml,titulo_shopee,titulo_tiktok,descricao,
                  preco_premium,preco_classico,preco_shopee,preco_tiktok,user,prioridade,prazo):
    with con() as c:
        t=now()
        c.execute("""INSERT INTO produtos(sku,criado_em,descricao) VALUES(%s,%s,%s)
                     ON CONFLICT (sku) DO UPDATE SET descricao=EXCLUDED.descricao""",(sku,t,descricao))
        n=c.execute("SELECT COALESCE(MAX(numero),0)n FROM anuncios WHERE sku=%s",(sku,)).fetchone()["n"]
        for idx,canal in enumerate(canais,1):
            if canal.startswith("MERCADO LIVRE"):
                tits=titulos_ml
                pp,pc=preco_premium,preco_classico
            elif canal.startswith("SHOPEE"):
                tits=[titulo_shopee]
                pp=pc=None
            else:
                tits=[titulo_tiktok]
                pp=pc=None
            ps=preco_shopee if canal.startswith("SHOPEE") else None
            pt=preco_tiktok if canal.startswith("TIKTOK") else None
            aid=c.execute("""INSERT INTO anuncios(
                sku,numero,titulo,descricao,preco,preco_premium,preco_classico,preco_shopee,preco_tiktok,canal,
                etapa,status,criado_em,atualizado_em,entrada_etapa_em,prioridade,prazo)
                VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,'BASE','AGUARDANDO',%s,%s,%s,%s,%s)
                RETURNING id""",
                (sku,n+idx,tits[0],descricao,pc,pp,pc,ps,pt,canal,t,t,t,prioridade,prazo)).fetchone()["id"]
            for ordem,titulo in enumerate(tits,1):
                c.execute("INSERT INTO anuncio_titulos(anuncio_id,ordem,titulo) VALUES(%s,%s,%s)",(aid,ordem,titulo))
            log(c,aid,"BASE","ANÚNCIO CRIADO",f"{user['nome']} | {canal}")

